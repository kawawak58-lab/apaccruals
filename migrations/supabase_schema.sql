create or replace function public.get_next_control_number()
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  v_prefix text;
  v_value integer;
  v_padding integer;
begin
  update public.control_number_sequence
  set
    last_value = last_value + 1,
    updated_at = timezone('utc', now())
  where id = true
  returning prefix, last_value, padding
  into v_prefix, v_value, v_padding;

  return v_prefix || lpad(v_value::text, v_padding, '0');
end;
$$;

