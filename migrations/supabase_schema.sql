      trim(v_line->>'profitcenter_code'), nullif(trim(v_line->>'profitcenter_name'), ''),
      trim(v_line->>'transaction_type'), nullif(trim(v_line->>'vat'), ''),
      nullif(trim(v_line->>'tax_code'), ''), trim(v_line->>'remarks')
    );
  end loop;
  return true;
end;
