create or replace function public.ensure_user_profile(
  p_display_name text default null
)
returns table (
  id bigint,
  auth_user_id uuid,
  email text,
  display_name text,
  usergroup text,
  can_update_control_number boolean,
  can_update_setup boolean,
  created_at timestamptz,
  updated_at timestamptz,
  last_login_at timestamptz
)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_email text := trim(coalesce(auth.jwt()->>'email', ''));
  v_display_name text := nullif(trim(coalesce(p_display_name, '')), '');
  v_existing public.users%rowtype;
begin
  if auth.uid() is null then
    raise exception 'Authenticated user is required';
  end if;

  if v_email = '' then
    raise exception 'Authenticated email is required';
  end if;

  select *
  into v_existing
  from public.users u
  where u.auth_user_id = auth.uid()
     or lower(u.email) = lower(v_email)
  order by case when u.auth_user_id = auth.uid() then 0 else 1 end
  limit 1;

  if not found then
    insert into public.users (
      auth_user_id,
      email,
      display_name,
      usergroup,
      can_update_control_number,
      can_update_setup,
      last_login_at
    )
    values (
      auth.uid(),
      v_email,
      coalesce(v_display_name, split_part(v_email, '@', 1)),
      'accrual_user',
      false,
      false,
      timezone('utc', now())
    )
    returning * into v_existing;
  else
    update public.users
    set
      auth_user_id = coalesce(v_existing.auth_user_id, auth.uid()),
      display_name = coalesce(v_display_name, nullif(trim(v_existing.display_name), ''), split_part(v_email, '@', 1)),
      last_login_at = timezone('utc', now())
    where id = v_existing.id
    returning * into v_existing;
  end if;

  return query
  select
    v_existing.id,
    v_existing.auth_user_id,
    v_existing.email,
    v_existing.display_name,
    v_existing.usergroup,
    v_existing.can_update_control_number,
    v_existing.can_update_setup,
    v_existing.created_at,
    v_existing.updated_at,
    v_existing.last_login_at;
end;
$$;

revoke all on function public.ensure_user_profile(text) from public;
grant execute on function public.ensure_user_profile(text) to authenticated, service_role;

create or replace function public.submit_accrual(
  p_header jsonb,
  p_line_items jsonb
)
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  v_control_number text;
  v_submission_id bigint;
  v_line jsonb;
begin
  if p_header is null then
    raise exception 'Header payload is required';
  end if;

  if p_line_items is null or jsonb_typeof(p_line_items) <> 'array' or jsonb_array_length(p_line_items) = 0 then
    raise exception 'At least one line item is required';
  end if;

  v_control_number := public.get_next_control_number();

  insert into public.accrual_submissions (
    control_number,
    maker,
    requester_email,
    expense_class,
    company,
    supplier_code,
    supplier_name,
    invoice_no,
    status,
    submitted_at
  )
  values (
    v_control_number,
    coalesce(nullif(p_header->>'maker', ''), coalesce(p_header->>'requester_email', '')),
    coalesce(p_header->>'requester_email', ''),
    coalesce(p_header->>'expense_class', ''),
    coalesce(p_header->>'company', ''),
    coalesce(p_header->>'supplier_code', ''),
    coalesce(p_header->>'supplier_name', ''),
    nullif(p_header->>'invoice_no', ''),
    coalesce((p_header->>'status')::integer, 0),
    timezone('utc', now())
  )
  returning id into v_submission_id;

  for v_line in
    select value
    from jsonb_array_elements(p_line_items)
  loop
    insert into public.accrual_submission_lines (
      submission_id,
      line_number,
      gross_amount,
      glaccount_code,
      glaccount_name,
      profitcenter_code,
      profitcenter_name,
      transaction_type,
      vat,
      tax_code,
      remarks
    )
    values (
      v_submission_id,
      coalesce((v_line->>'line_number')::integer, 0),
      coalesce((v_line->>'gross_amount')::numeric, 0),
      coalesce(v_line->>'glaccount_code', ''),
      nullif(v_line->>'glaccount_name', ''),
      coalesce(v_line->>'profitcenter_code', ''),
      nullif(v_line->>'profitcenter_name', ''),
      coalesce(v_line->>'transaction_type', ''),
      nullif(v_line->>'vat', ''),
      nullif(v_line->>'tax_code', ''),
      coalesce(v_line->>'remarks', '')
    );
  end loop;

  return v_control_number;
end;
$$;

revoke all on function public.submit_accrual(jsonb, jsonb) from public;
grant execute on function public.submit_accrual(jsonb, jsonb) to anon, authenticated, service_role;

